/**
 * 行测/职测章节 → 粉笔树节点 映射（build 与 server 共用）
 * 返回 { group, sub, leaf } 或 null（无法匹配 → 需内容分类）
 *
 * 匹配规则（2026-08 修复）：
 *  1) 先精确匹配（ch === key），再按 key 长度降序做 includes 匹配，
 *     避免「数量关系」抢先匹配「数量关系（数学运算）/数量关系与资料分析」等长章节名。
 *  2) 「言语理解 / 言语表达与理解 / 言语能力与表达」等宽泛章节名内部
 *     混有选词填空/片段阅读/语句表达，一律归「全部」走内容分类（classifyYanyu），
 *     不得直接映射到某个子模块（否则大量选词填空题被误归片段阅读）。
 *  3) 「数量关系与资料分析 / 数理能力 / 数量分析」为数量+资料混合章节，
 *     归「全部」走内容分类（classifyXingceSub 内先判资料特征再判数量）。
 *  4) 职测特有章节名（2026-08 职测分类修复）：
 *     - 「言语应用 / 言语运用」= 联考B类言语题（粉笔 B 类叫法）→ 言语理解与表达
 *     - 「综合分析」按试卷类别区分：联考B类 = 篇章阅读/文章阅读（言语！），
 *       联考C类 = 数学运算（数量）；ctx.category 传入卷类做区分，
 *       不传 ctx（server 章节挂载场景）时保守归数量关系（C 类为多数）。
 * @param {string} ch 章节名
 * @param {{category?: string}} [ctx] 试卷类别上下文（职测 B/C 类区分用）
 */
export function mapChapterToNode(ch, ctx = {}) {
  const G = '言语理解与表达', P = '判断推理', N = '数量关系', Z = '资料分析', C = '常识判断', ZL = '政治理论';
  const m = (group, sub, leaf) => ({ group, sub, leaf: leaf ?? null });
  // 职测 B 类「综合分析」= 篇章阅读（文章阅读），与 C 类（数学运算）不同
  if (ch === '综合分析') {
    return ctx.category === '联考B类' ? m(G, '全部') : m(N, '全部');
  }
  const map = [
    // 言语理解与表达
    ['言语理解与表达', m(G, '全部')], ['言语理解与表达能力', m(G, '全部')],
    // 职测 B 类特有章节名（2026-08 修复）：B 类言语题（粉笔叫法）
    ['言语应用', m(G, '全部')], ['言语运用', m(G, '全部')],
    // 宽泛章节名（混有填空/阅读/语句表达）→ 内容分类细分
    ['言语理解', m(G, '全部')], ['言语表达与理解', m(G, '全部')], ['言语能力与表达', m(G, '全部')],
    ['选词填空', m(G, '逻辑填空')], ['实词填空', m(G, '逻辑填空')], ['逻辑填空', m(G, '逻辑填空')],
    ['阅读理解', m(G, '片段阅读')], ['段落阅读', m(G, '片段阅读')], ['语句表达', m(G, '语句表达')],
    // 判断推理
    ['判断推理', m(P, '全部')], ['判断推理能力', m(P, '全部')], ['推理判断', m(P, '全部')],
    ['图形推理', m(P, '图形推理')], ['定义判断', m(P, '定义判断')], ['类比推理', m(P, '类比推理')],
    ['逻辑判断', m(P, '逻辑判断')], ['逻辑推理', m(P, '逻辑判断')], ['演绎推理', m(P, '逻辑判断')],
    // 江苏/浙江等特色模块：字符/数字符号查找题，独立节点（见 fenbi-tree.mjs 判断推理组）
    ['知觉速度与准确性', m(P, '知觉速度与准确性')],
    // 数量关系（精确章节名在前，避免前缀抢先）
    ['数量关系（数学运算）', m(N, '数学运算')], ['数量关系（数字推理）', m(N, '数学运算')],
    ['数量关系与资料分析', m(N, '全部')], // 混合章节 → 内容分类
    ['数量关系', m(N, '全部')], ['数理能力', m(N, '全部')], ['数量分析', m(N, '全部')],
    ['数学运算', m(N, '数学运算')], ['数字推理', m(N, '数学运算')],
    // 资料分析
    ['资料分析', m(Z, '全部')], ['资料分斩', m(Z, '全部')],
    // 注意：「综合分析能力」是上海卷常识/时政多选题章节，归常识判断走内容分类
    ['综合分析能力', m(C, '全部')],
    // 常识判断
    ['常识判断', m(C, '全部')], ['常识判断（单选题）', m(C, '全部')], ['常识判断（多选题）', m(C, '全部')],
    ['常识', m(C, '全部')], ['常识应用', m(C, '全部')], ['常识应用能力', m(C, '全部')],
    ['常识部分', m(C, '全部')], ['基本常识', m(C, '全部')],
    ['公共基础知识', m(C, '全部')], ['公共基础知识-单项选择题', m(C, '全部')],
    ['公共基础知识-判断题', m(C, '全部')], ['公共基础知识-多项选择题', m(C, '全部')],
    ['综合知识', m(C, '全部')], ['综合基础知识', m(C, '全部')],
    ['法律基础知识', m(C, '法律常识')],
    ['科学推理', m(C, '科技常识')], ['科学素养', m(C, '科技常识')],
    // 政治理论
    ['政治理论', m(ZL, '全部')],
  ];
  // 1) 精确匹配优先
  for (const [key, v] of map) {
    if (ch === key) return v;
  }
  // 2) includes 兜底：按 key 长度降序（长章节名优先，避免「数量关系」抢先「数量关系（数学运算）」）
  const sorted = [...map].sort((a, b) => b[0].length - a[0].length);
  for (const [key, v] of sorted) {
    if (ch.includes(key)) return v;
  }
  return null;
}
